static uint8_t reverse_bits(uint8_t b)
{
    b = ((b & 0xf0u) >> 4) | ((b & 0x0fu) << 4);
    b = ((b & 0xccu) >> 2) | ((b & 0x33u) << 2);
    b = ((b & 0xaau) >> 1) | ((b & 0x55u) << 1);
    return b;
}

vram_result_t vga_text_begin_frame(void)
{
    vram_result_t result;
    const uint32_t poll_budget = 2000000u;

    result = vram_wait_ready(poll_budget);
    if (result != VRAM_RESULT_OK) return result;
    vram_clear_events(VRAM_STATUS_VSYNC);
    result = vram_wait_vsync(poll_budget);
    if (result != VRAM_RESULT_OK) return result;
    result = vram_start_operation(VRAM_CTRL_SWAP | VRAM_CTRL_HW_CLEAR);
    if (result != VRAM_RESULT_OK) return result;
    return vram_wait_operation(poll_budget);
}

void vga_text_puts(uint32_t word_x, uint32_t y, const char *str)
{
    uint32_t len = 0u;
    uint32_t i;

    while (str[len] != '\0') {
        len++;
    }

    for (i = 0u; i < len; i += 4u) {
        uint32_t dy;
        if (word_x >= 20u) {
            break;
        }
        for (dy = 0u; dy < 8u; dy++) {
            uint32_t py = y + dy;
            uint32_t row = 0u;
            uint32_t j;
            if (py >= 480u) {
                break;
            }
            for (j = 0u; j < 4u; j++) {
                uint8_t ch = 32u;
                uint32_t idx = 0u;
                if ((i + j) < len) {
                    ch = (uint8_t)str[i + j];
                }
                if (ch >= 32u && ch <= 90u) {
                    idx = (uint32_t)ch - 32u;
                }
                row |= ((uint32_t)reverse_bits(font8x8[idx][dy]) << (j * 8u));
            }
            vram_write_word((py * 20u) + word_x, row);
        }
        word_x++;
    }
}

static char hex_digit(uint32_t value)
{
    value &= 0x0fu;
    return (char)(value < 10u ? ('0' + value) : ('A' + (value - 10u)));
}

void vga_text_put_hex8(uint32_t word_x, uint32_t y, uint8_t value)
{
    char s[3];
    s[0] = hex_digit((uint32_t)value >> 4);
    s[1] = hex_digit((uint32_t)value);
    s[2] = '\0';
    vga_text_puts(word_x, y, s);
}

void vga_text_put_hex16(uint32_t word_x, uint32_t y, uint16_t value)
{
    char s[5];
    s[0] = hex_digit((uint32_t)value >> 12);
    s[1] = hex_digit((uint32_t)value >> 8);
    s[2] = hex_digit((uint32_t)value >> 4);
    s[3] = hex_digit((uint32_t)value);
    s[4] = '\0';
    vga_text_puts(word_x, y, s);
}

void vga_text_put_hex32(uint32_t word_x, uint32_t y, uint32_t value)
{
    char s[9];
    uint32_t i;
    for (i = 0u; i < 8u; i++) {
        s[i] = hex_digit(value >> (28u - (i * 4u)));
    }
    s[8] = '\0';
    vga_text_puts(word_x, y, s);
}
